// Writes src/lib/schema-sql.ts: the SQL that creates every table, generated from prisma/schema.prisma.
// The live server uses it to set up an empty database the first time it starts.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execSync("npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script", {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "ignore"],
});
writeFileSync(
  "src/lib/schema-sql.ts",
  `// Generated by scripts/schema-sql.mjs from prisma/schema.prisma. Do not edit by hand.\nexport const SCHEMA_SQL = ${JSON.stringify(sql)};\n`
);
console.log("Wrote src/lib/schema-sql.ts");
